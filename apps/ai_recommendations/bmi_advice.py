DISCLAIMER = _("คำแนะนำนี้เป็นข้อมูลสุขภาพทั่วไป ไม่ใช่การวินิจฉัยหรือการรักษาทางการแพทย์")


def bmi_advice(bmi):
    """Advice for one BMI value: label, what to eat, how to care, what to watch."""
    try:
        value = float(bmi)
    except (TypeError, ValueError):
        return None
    if value <= 0:
        return None
    band = next(b for b in BANDS if b["max"] is None or value < b["max"])
    return {
        "bmi": round(value, 1),
        "key": band["key"],
        "label": str(band["label"]),
        "eat": [str(t) for t in band["eat"]],
        "care": [str(t) for t in band["care"]],
        "caution": [str(t) for t in band["caution"]],
        "disclaimer": str(DISCLAIMER),
    }


